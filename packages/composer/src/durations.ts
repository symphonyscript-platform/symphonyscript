/**
 * Tick constants for common note durations at PPQ 480.
 *
 * Use directly for edge cases where string durations don't cover the need.
 * For most cases, prefer string notation: `'4n'`, `'8n.'`, `'4t'`.
 */

/** Whole note (4 beats) = 1920 ticks */
export const WHOLE = 1920
/** Half note (2 beats) = 960 ticks */
export const HALF = 960
/** Quarter note (1 beat) = 480 ticks */
export const QUARTER = 480
/** Eighth note (1/2 beat) = 240 ticks */
export const EIGHTH = 240
/** Sixteenth note (1/4 beat) = 120 ticks */
export const SIXTEENTH = 120
/** Thirty-second note (1/8 beat) = 60 ticks */
export const THIRTY_SECOND = 60
